#!/usr/bin/env python3
"""
process_bacdive_genus.py
========================
Extract unique genus names from an LPSN GSS CSV and write them as the ``taxa``
list in ``bacdive/all_taxa_medium.yaml`` (target: medium_growth).

USAGE:
    python scripts/process_bacdive_genus.py
    python scripts/process_bacdive_genus.py \\
        --csv data/external/lpsn_gss_2026-08-17.csv \\
        --out bacdive/all_taxa_medium.yaml
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CSV = ROOT / "data" / "external" / "lpsn_gss_2026-08-17.csv"
DEFAULT_OUT = ROOT / "bacdive" / "all_taxa_medium.yaml"


def parse_args(argv=None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--csv",
        type=Path,
        default=DEFAULT_CSV,
        help=f"LPSN GSS CSV with a genus_name column (default: {DEFAULT_CSV})",
    )
    p.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help=f"Output taxa YAML (default: {DEFAULT_OUT})",
    )
    p.add_argument(
        "--column",
        default="genus_name",
        help="Column containing genus names (default: genus_name)",
    )
    return p.parse_args(argv)


def unique_genus_names(csv_path: Path, column: str) -> list[str]:
    if not csv_path.is_file():
        raise FileNotFoundError(f"CSV not found: {csv_path}")

    names: set[str] = set()
    with csv_path.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames is None or column not in reader.fieldnames:
            raise ValueError(
                f"Column {column!r} not in CSV fields: {reader.fieldnames}"
            )
        for row in reader:
            name = (row.get(column) or "").strip()
            if name:
                names.add(name)

    return sorted(names)


def write_taxa_yaml(out_path: Path, taxa: list[str], target: str = "medium_growth") -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    # Match the indented list style used in bacdive/all_taxa_metabolite.yaml
    lines = [
        f"# BacDive medium growth dataset using all genus ({len(taxa)})",
        "# Generated by scripts/process_bacdive_genus.py — do not edit by hand.",
        f"target: {target}",
        "",
        "taxa:",
    ]
    lines.extend(f"  - {name}" for name in taxa)
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf-8")


def main(argv=None) -> int:
    args = parse_args(argv)
    taxa = unique_genus_names(args.csv, args.column)
    print(f"Unique {args.column} values: {len(taxa)}")
    write_taxa_yaml(args.out, taxa)
    print(f"Wrote {len(taxa)} taxa -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
